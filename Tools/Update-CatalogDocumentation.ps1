[CmdletBinding()]
param([switch] $Check)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$repository = Split-Path $PSScriptRoot -Parent
$definitions = Join-Path $repository 'SynixApp/Database/GameDefinitions'
$readmePath = Join-Path $repository 'README.md'
$listPath = Join-Path $repository 'docs/Game-List.md'

function Get-Field($Definition, [string] $Name, $Default = '') {
    $property = $Definition.PSObject.Properties[$Name]
    if ($null -eq $property) { return $Default }
    return $property.Value
}
function Escape-Cell([string] $Value) {
    return $Value.Replace('|', '&#124;').Replace('<', '&lt;').Replace('>', '&gt;').Replace("`r", ' ').Replace("`n", ' ')
}

$profiles = @(Get-ChildItem -LiteralPath $definitions -Recurse -File -Filter '*.game.json' | ForEach-Object {
    $definition = Get-Content -LiteralPath $_.FullName -Raw -Encoding UTF8 | ConvertFrom-Json
    if (!$definition.id -or !$definition.game) { throw "Invalid game definition: $($_.FullName)" }
    [pscustomobject]@{ Definition = $definition; File = $_.FullName }
} | Sort-Object { $_.Definition.catalogOrder }, { $_.Definition.id })
if ($profiles.Count -eq 0) { throw 'The game catalog is empty.' }
if (@($profiles | Group-Object { $_.Definition.id } | Where-Object Count -gt 1).Count) { throw 'Duplicate game profile IDs.' }

$count = $profiles.Count
$steamCount = @($profiles | Where-Object { [string]$_.Definition.appId -match '^[1-9][0-9]*$' }).Count
$lines = [Collections.Generic.List[string]]::new()
$lines.AddRange([string[]]@(
    '<!-- Generated by Tools/Update-CatalogDocumentation.ps1. Do not edit this table by hand. -->',
    '# Built-in game-server profiles', '',
    "Synix currently includes **$count profiles**: **$steamCount SteamCMD profiles** and **$($count - $steamCount) non-Steam profiles**.", '',
    'This is the catalog shipped in this branch, not a claim that every game has been installed and live-tested.',
    'Steam IDs below are the download package IDs configured in Synix, not necessarily the client game IDs.',
    'Some packages legitimately serve multiple profiles; the branch or app configuration selects the required server.',
    'A link to SteamDB is a reference for that configured ID, not a claim of a new online verification.', '',
    '| Profile | Server download | Steam branch / app configuration | Steam account required |',
    '|---|---|---|---|'
))
foreach ($profile in $profiles) {
    $game = $profile.Definition
    $relative = [IO.Path]::GetRelativePath($repository, $profile.File).Replace('\', '/')
    $label = Escape-Cell ([string]$game.game)
    $appId = [string]$game.appId
    $steam = $appId -match '^[1-9][0-9]*$'
    $download = if ($steam) { "[SteamCMD $appId](https://steamdb.info/app/$appId/)" } else { 'Non-Steam download' }
    $selectors = @()
    $branch = [string](Get-Field $game 'steamBranch')
    $config = [string](Get-Field $game 'steamAppConfig')
    if ($branch) { $selectors += 'Branch: ' + (Escape-Cell $branch) }
    if ($config) { $selectors += 'App config: ' + (Escape-Cell $config) }
    $selector = if ($selectors.Count) { $selectors -join '; ' } elseif ($steam) { 'Default' } else { '—' }
    $login = if (!$steam) { '—' } elseif (Get-Field $game 'requiresSteamLogin' $false) { 'Yes' } else { 'No' }
    $lines.Add("| [$label](../$relative) | $download | $selector | $login |")
}
$lines.AddRange([string[]]@('', '## Keeping this page current', '',
    'Run `pwsh -File Tools/Update-CatalogDocumentation.ps1` after changing the game database.',
    'Use `-Check` for a read-only drift check. The GitHub workflow runs that check before building.',
    'The README count and this page are updated together from the same JSON files.', ''))
$generated = $lines -join "`n"
$originalReadme = [IO.File]::ReadAllText($readmePath)
$readme = $originalReadme
$replacements = @(
    @('Game%20Server%20Profiles-\d+-', "Game%20Server%20Profiles-$count-"),
    @('Select from \d+ built-in server profiles', "Select from $count built-in server profiles"),
    @('## 🎮 \d+ Built-In Server Profiles', "## 🎮 $count Built-In Server Profiles"),
    @('Synix includes \*\*\d+ built-in dedicated game-server profiles\*\*', "Synix includes **$count built-in dedicated game-server profiles**")
)
foreach ($replacement in $replacements) {
    if ([regex]::Matches($readme, $replacement[0]).Count -ne 1) { throw "README count marker changed: $($replacement[0])" }
    $readme = [regex]::Replace($readme, $replacement[0], $replacement[1])
}
$listMatches = (Test-Path -LiteralPath $listPath) -and
    [IO.File]::ReadAllText($listPath).ReplaceLineEndings("`n") -ceq $generated
if ($Check) {
    if (!$listMatches -or $readme -cne $originalReadme) { throw 'Catalog documentation is out of date. Run Tools/Update-CatalogDocumentation.ps1.' }
    Write-Output "Catalog documentation is current ($count profiles)."
    return
}
[IO.Directory]::CreateDirectory((Split-Path $listPath -Parent)) | Out-Null
if (!$listMatches) { [IO.File]::WriteAllText($listPath, $generated, [Text.UTF8Encoding]::new($false)) }
if ($readme -cne $originalReadme) { [IO.File]::WriteAllText($readmePath, $readme, [Text.UTF8Encoding]::new($false)) }
Write-Output "Updated catalog documentation ($count profiles)."
