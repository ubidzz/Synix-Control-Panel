using System.Globalization;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using Synix_Control_Panel.SynixApp.Localization;

// Developer-only, offline and read-only. This tool is not part of the app's
// publish output and does not access settings, server files or online services.
Console.OutputEncoding = new UTF8Encoding(false);
try
{
	bool markdown = args.Contains("--markdown", StringComparer.Ordinal);
	if (args.Any(arg => arg is not ("--markdown" or "--check")))
		throw new ArgumentException("Usage: dotnet run --project Tools/LanguageCoverage -- [--markdown] [--check]");

	string directory = FindCatalogDirectory();
	Dictionary<string, string> english = ReadCatalog(Path.Combine(directory, "Strings.resx"));
	List<Catalog> catalogs = [new("en-US", LanguageCatalogPolicy.CheckCatalog(english, english, isEnglish: true))];
	foreach (string path in Directory.EnumerateFiles(directory, "Strings.*.resx").Order(StringComparer.Ordinal))
	{
		string code = Path.GetFileName(path)["Strings.".Length..^".resx".Length];
		CultureInfo culture = CultureInfo.GetCultureInfo(code);
		catalogs.Add(new(culture.Name, LanguageCatalogPolicy.CheckCatalog(english, ReadCatalog(path),
			isEnglish: culture.TwoLetterISOLanguageName == "en")));
	}

	string[] complete = catalogs.Where(c => c.Coverage.State == LanguageCatalogPolicy.CatalogState.Complete)
		.Select(c => c.Code).ToArray();
	CultureInfo[] cultures = CultureInfo.GetCultures(CultureTypes.NeutralCultures)
		.Where(culture => culture.Name.Length > 0)
		.DistinctBy(culture => culture.Name, StringComparer.OrdinalIgnoreCase)
		.OrderBy(culture => culture.Name, StringComparer.Ordinal).ToArray();
	Target[] targets = cultures.Select(culture => new Target(culture,
		LanguageCatalogPolicy.FindBestCatalog(culture.Name, complete))).ToArray();
	int baseLanguages = cultures.Select(c => c.TwoLetterISOLanguageName).Distinct(StringComparer.Ordinal).Count();
	int missingTargets = targets.Count(t => t.Catalog == null);
	int requiredCount = english.Keys.Count(LanguageCatalogPolicy.IsTextKey);

	if (markdown)
	{
		Console.WriteLine("<!-- Generated by Tools/LanguageCoverage with --markdown. This is a backlog, not an app-language menu. -->");
		Console.WriteLine("# Windows/.NET language coverage\n");
		Console.WriteLine("Target: every non-invariant neutral language reported by Windows/.NET, retaining separate writing-system entries. Regional settings resolve to an appropriate catalog where available; they are not automatically separate translations.\n");
		Console.WriteLine($"This snapshot contains **{targets.Length} language/writing-system targets** across **{baseLanguages} base language codes**. Synix has **{complete.Length} structurally complete catalogs, including English**, with **{requiredCount:N0} required text entries per catalog**. **{missingTargets} target entries still need a translation**. Generic aliases (for example Chinese and Norwegian) can share an existing catalog; target counts are not counts of distinct translations.\n");
		Console.WriteLine("Only complete, non-preview catalogs are eligible for the app's language picker. Empty entries, missing or unexpected source keys, and untranslated English-only copies are rejected. Key coverage does not certify translation accuracy: terminology, technical syntax, layout and accessibility still require review. This inventory does not add new translations or claim that right-to-left layout is finished.\n");
		Console.WriteLine($"Inventory runtime: .NET {Environment.Version}; {Cell(Environment.OSVersion.VersionString)}. Available cultures depend on the installed Windows/.NET globalization data; regenerate on the supported release environment rather than treating this number as a permanent global total. See [Microsoft's CultureInfo documentation](https://learn.microsoft.com/en-us/dotnet/api/system.globalization.cultureinfo) and [Windows Forms bidirectional layout guidance](https://learn.microsoft.com/en-us/dotnet/desktop/winforms/advanced/bi-directional-support-for-windows-forms-applications).\n");
		Console.WriteLine("## Current catalogs\n");
		Console.WriteLine("| Catalog | Source coverage | Missing/blank keys | Unexpected keys |\n|---|---|---:|---:|");
		foreach (Catalog catalog in catalogs.OrderBy(c => c.Code, StringComparer.Ordinal))
			Console.WriteLine($"| {Cell(catalog.Code)} | {catalog.Coverage.State} | {catalog.Coverage.MissingKeys.Count} | {catalog.Coverage.UnexpectedKeys.Count} |");
		Console.WriteLine("\n## Translation and layout backlog\n");
		Console.WriteLine("An existing catalog is a language fallback, not a claim of country-specific wording. Every new catalog also needs a font, layout and live-switching review. RTL rows additionally need bidirectional controls, mirrored layouts where appropriate, and checks that passwords, paths and commands remain unmodified.\n");
		Console.WriteLine("| Target | Language / writing system | Native name | Direction | Existing catalog / remaining work |\n|---|---|---|---|---|");
		foreach (Target target in targets)
		{
			string status = target.Catalog == null ? "Translation needed" : $"Catalog: {target.Catalog}";
			if (NeedsRtlReview(target.Culture)) status += "; RTL layout review needed";
			Console.WriteLine($"| {Cell(target.Culture.Name)} | {Cell(target.Culture.EnglishName)} | {Cell(target.Culture.NativeName)} | {(NeedsRtlReview(target.Culture) ? "RTL" : "LTR")} | {status} |");
		}
		Console.WriteLine("\n## Updating the inventory\n");
		Console.WriteLine("Run `dotnet run --project Tools/LanguageCoverage -- --markdown` from the repository root to produce a fresh report. The tool only prints output; it does not change source files. Run with `--check` to reject incomplete catalogs that have been added to the source tree. Missing target languages remain a backlog and do not fail that check.\n");
		Console.WriteLine("Use `SynixApp/Localization/README.md` for catalog format, protected technical content and the release checklist. No translation API or PowerShell script is required by the installed app.");
	}
	else
	{
		Console.WriteLine($"{complete.Length} complete catalogs; {requiredCount} required entries; {targets.Length} Windows/.NET targets; {missingTargets} target entries awaiting translation.");
		foreach (Catalog catalog in catalogs.Where(c => c.Coverage.State != LanguageCatalogPolicy.CatalogState.Complete))
			Console.WriteLine($"{catalog.Code}: {catalog.Coverage.State}; missing/blank={catalog.Coverage.MissingKeys.Count}, unexpected={catalog.Coverage.UnexpectedKeys.Count}");
	}
	return args.Contains("--check", StringComparer.Ordinal)
		&& catalogs.Any(c => c.Coverage.State != LanguageCatalogPolicy.CatalogState.Complete) ? 1 : 0;
}
catch (Exception error) when (error is IOException or UnauthorizedAccessException or ArgumentException or XmlException)
{
	Console.Error.WriteLine(error.Message);
	return 1;
}

static string FindCatalogDirectory()
{
	for (DirectoryInfo? current = new(Environment.CurrentDirectory); current != null; current = current.Parent)
	{
		string candidate = Path.Combine(current.FullName, "SynixApp", "Localization");
		if (File.Exists(Path.Combine(candidate, "Strings.resx"))) return candidate;
	}
	throw new DirectoryNotFoundException("Run this tool from the Synix repository or one of its subfolders.");
}

static Dictionary<string, string> ReadCatalog(string path)
{
	using XmlReader reader = XmlReader.Create(path, new XmlReaderSettings
	{
		DtdProcessing = DtdProcessing.Prohibit, XmlResolver = null
	});
	XDocument document = XDocument.Load(reader);
	Dictionary<string, string> result = new(StringComparer.Ordinal);
	foreach (XElement entry in document.Root?.Elements("data") ?? [])
	{
		string? key = (string?)entry.Attribute("name");
		if (string.IsNullOrWhiteSpace(key) || entry.Attribute("type") != null || entry.Attribute("mimetype") != null)
			throw new InvalidDataException($"Unsupported resource in {Path.GetFileName(path)}; language catalogs must use named text entries.");
		if (!result.TryAdd(key, (string?)entry.Element("value") ?? ""))
			throw new InvalidDataException($"Duplicate key '{key}' in {Path.GetFileName(path)}.");
	}
	return result;
}

static bool NeedsRtlReview(CultureInfo culture) => culture.TextInfo.IsRightToLeft
	|| LanguageCatalogPolicy.GetExplicitScript(culture.Name) is "Arab" or "Hebr" or "Thaa" or "Syrc" or "Nkoo" or "Adlm" or "Rohg";

static string Cell(string value) => value.Replace("|", "&#124;").Replace("<", "&lt;")
	.Replace(">", "&gt;").Replace("\r", " ").Replace("\n", " ");

internal sealed record Catalog(string Code, LanguageCatalogPolicy.CatalogCoverage Coverage);
internal sealed record Target(CultureInfo Culture, string? Catalog);
